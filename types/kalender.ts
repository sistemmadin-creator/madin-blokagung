export interface AturanKegiatanMetadata {
  kode: KodeKegiatanKalender;
  labelSingkat: string;
  namaKegiatan: string;
  bgHex: string;
  textHex: string;
  borderHex: string;
  isStriped?: boolean;
  defaultIsLiburKbm: boolean;
  kategoriLiburAbsensi: KategoriLiburAbsensi;
  deskripsiAturan: string;
}

export interface AgendaKalenderItem {
  /** Tanggal Masehi format YYYY-MM-DD (Kunci utama lintas Masehi & Hijriyah) */
  tanggalMasehi: string;
  kode: KodeKegiatanKalender;
  namaKegiatan: string;
  /** Apakah pada tanggal ini sesi KBM reguler diliburkan di menu Absensi (Gambar 3) */
  isLiburKbm: boolean;
  kategoriLibur: KategoriLiburAbsensi;
  catatan?: string;
  isAutoGenerated?: boolean;
  updatedAt?: string;
  updatedBy?: string;
}

export interface TahunAjaranKalenderConfig {
  /** Contoh: "2025/2026" */
  tahunAjaranMasehi: string;
  /** Contoh: "1446/1447" */
  tahunAjaranHijriyah: string;
  /** Tahun awal Masehi, misal 2025 (Juni 2025 s/d Juni 2026) */
  startYearMasehi: number;
  /** Tahun awal Hijriyah, misal 1446 (Dzulhijjah 1446 s/d Dzulhijjah 1447) */
  startYearHijriyah: number;
  /** Koreksi rukyatul hilal dalam satuan hari (-2 s/d +2) */
  hijriOffsetDays: number;
}

export interface SelKalenderGrid {
  tanggalMasehi: string; // YYYY-MM-DD
  dayMasehi: number;
  monthMasehi: number; // 1..12
  yearMasehi: number;
  dayHijri: number;
  monthHijri: number; // 1..12
  yearHijri: number;
  dayOfWeek: number; // 0 (Ahad) .. 6 (Sabtu)
  isCurrentMonth: boolean;
  isFriday: boolean;
  pasaranJawa: 'Legi' | 'Pahing' | 'Pon' | 'Wage' | 'Kliwon';
  agenda?: AgendaKalenderItem;
}

export interface BulanKalenderGrid {
  id: string;
  titleSidebar: string; // Contoh: "JUNI 2025" atau "DZULHIJJAH 46"
  subtitleHeader: string;
  monthNumber: number;
  yearNumber: number;
  sidebarVariant: 'amber' | 'lime';
  weeks: SelKalenderGrid[][];
}

